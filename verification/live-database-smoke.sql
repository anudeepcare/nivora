-- Rollback-only verification: synthetic accounts and rows never persist.
begin;
set local statement_timeout = '30s';
set local lock_timeout = '5s';
do $verification$
declare
  a uuid := gen_random_uuid();
  b uuid := gen_random_uuid();
  list_a uuid;
  import_id uuid := gen_random_uuid();
  plan_a uuid;
  plan_b uuid;
  run_a jsonb;
  denied boolean;
  changed integer;
  checks integer := 0;
  payload jsonb := '[{"symbol":"MSFT","quantity":2,"cost":100,"currency":"USD"}]';
begin
  insert into auth.users(id,aud,role,email,raw_app_meta_data,raw_user_meta_data)
  values(a,'authenticated','authenticated','auryn-test-'||a::text||'@example.invalid','{}','{}'),
        (b,'authenticated','authenticated','auryn-test-'||b::text||'@example.invalid','{}','{}');
  perform set_config('request.jwt.claim.sub',a::text,true);
  perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated','is_anonymous',false)::text,true);
  execute 'set local role authenticated';
  assert auth.uid()=a, 'Unexpected account context'; checks:=checks+1;
  assert not has_table_privilege(current_user,'public.auryn_documents','TRUNCATE'), 'Destructive default grant retained'; checks:=checks+1;
  assert not has_table_privilege(current_user,'public.auryn_paper_plans','INSERT'), 'Client paper plan write grant retained'; checks:=checks+1;
  perform public.auryn_set_watch('MSFT',true);
  perform public.auryn_set_watch('MSFT',true);
  assert (select count(*) from public.watchlist_items where user_id=a and symbol='MSFT')=1, 'Duplicate watch item'; checks:=checks+1;
  select id into list_a from public.watchlists where user_id=a;
  insert into public.auryn_documents(user_id,kind,key,body) values(a,'note','MSFT','{"thesis":"test"}');
  update public.auryn_documents set body='{"thesis":"updated"}' where user_id=a and kind='note' and key='MSFT';
  assert (select body->>'thesis' from public.auryn_documents where user_id=a and key='MSFT')='updated', 'Own note write/read failed'; checks:=checks+1;
  insert into public.auryn_observations(user_id,symbol,snapshot_id,payload) values(a,'MSFT','live-smoke','{"original":true}');
  begin
    update public.auryn_observations set payload='{"original":false}' where user_id=a;
  exception when insufficient_privilege then null;
  end;
  assert (select observation.payload->>'original' from public.auryn_observations observation where user_id=a)='true', 'Observation was mutable'; checks:=checks+1;
  insert into public.auryn_alert_events(user_id,rule_key,event_key,symbol,title,detail,snapshot_id)
  values(a,'test-rule','test-event','MSFT','Test','Test','live-smoke');
  update public.auryn_alert_events set read_at=now() where user_id=a;
  assert (select read_at is not null from public.auryn_alert_events where user_id=a), 'Alert read state failed'; checks:=checks+1;
  perform set_config('request.jwt.claim.sub',b::text,true);
  perform set_config('request.jwt.claims',jsonb_build_object('sub',b,'role','authenticated','is_anonymous',false)::text,true);
  assert (select count(*) from public.auryn_documents where user_id=a)=0, 'Cross-account notes exposed'; checks:=checks+1;
  assert (select count(*) from public.auryn_observations where user_id=a)=0, 'Cross-account observations exposed'; checks:=checks+1;
  assert (select count(*) from public.auryn_alert_events where user_id=a)=0, 'Cross-account alerts exposed'; checks:=checks+1;
  denied:=false;
  begin insert into public.auryn_documents(user_id,kind,key,body) values(a,'note','AAPL','{}');
  exception when insufficient_privilege then denied:=true; end;
  assert denied, 'Cross-account note insert allowed'; checks:=checks+1;
  denied:=false;
  begin insert into public.watchlist_items(user_id,watchlist_id,symbol) values(b,list_a,'AAPL');
  exception when insufficient_privilege then denied:=true; end;
  assert denied, 'Foreign watchlist membership allowed'; checks:=checks+1;
  perform public.auryn_set_watch('MSFT',false);
  assert public.auryn_import_positions(import_id,payload)=1, 'Import failed'; checks:=checks+1;
  assert public.auryn_import_positions(import_id,payload)=1, 'Import replay failed'; checks:=checks+1;
  assert (select count(*) from public.portfolio_positions where user_id=b)=1, 'Import duplicated positions'; checks:=checks+1;
  denied:=false;
  begin perform public.auryn_import_positions(import_id,'[{"symbol":"AAPL","quantity":2,"cost":100,"currency":"USD"}]');
  exception when raise_exception then denied:=sqlerrm='Import identifier already used for different content'; end;
  assert denied, 'Changed import replay allowed'; checks:=checks+1;
  denied:=false;
  begin insert into public.auryn_paper_plans(user_id,body) values(b,'{}');
  exception when insufficient_privilege then denied:=true; end;
  assert denied, 'Client-created paper plan allowed'; checks:=checks+1;
  assert not has_function_privilege(current_user,'public.auryn_claim_paper(uuid,uuid,text)','EXECUTE'), 'Client can claim broker authority'; checks:=checks+1;
  assert not has_schema_privilege(current_user,'auryn_product_private','USAGE'), 'Private budget schema exposed'; checks:=checks+1;
  assert public.auryn_reserve_ai_request(), 'AI reservation 1 failed';
  assert public.auryn_reserve_ai_request(), 'AI reservation 2 failed';
  assert public.auryn_reserve_ai_request(), 'AI reservation 3 failed';
  assert not public.auryn_reserve_ai_request(), 'AI account cap exceeded'; checks:=checks+1;
  execute 'reset role';
  assert (select count(*) from public.watchlist_items where user_id=a and symbol='MSFT')=1, 'Foreign unsave changed owner data'; checks:=checks+1;
  execute 'set local role service_role';
  insert into public.auryn_paper_plans(user_id,body,enabled) values(a,'{}',true) returning id into plan_a;
  insert into public.auryn_paper_plans(user_id,body,enabled) values(a,'{}',true) returning id into plan_b;
  select public.auryn_claim_paper(plan_a,a,'verification-only') into run_a;
  assert run_a->>'status'='reserved', 'Paper reservation failed'; checks:=checks+1;
  denied:=false;
  begin perform public.auryn_claim_paper(plan_b,a,'verification-only');
  exception when raise_exception then denied:=sqlerrm='An unresolved paper run must be reconciled first'; end;
  assert denied, 'Concurrent paper claim allowed'; checks:=checks+1;
  delete from public.auryn_paper_lock where run_id=(run_a->>'id')::uuid;
  denied:=false;
  begin perform public.auryn_claim_paper(plan_a,a,'verification-only');
  exception when unique_violation then denied:=true; end;
  assert denied, 'Repeated monthly paper claim allowed'; checks:=checks+1;
  update public.auryn_paper_plans set enabled=false where id=plan_b;
  denied:=false;
  begin perform public.auryn_claim_paper(plan_b,a,'verification-only');
  exception when raise_exception then denied:=sqlerrm='Plan is paused or unavailable'; end;
  assert denied, 'Paused paper plan claimed'; checks:=checks+1;
  execute 'reset role';
  execute 'set local role authenticated';
  assert (select count(*) from public.auryn_paper_runs where user_id=a)=0, 'Cross-account paper runs exposed'; checks:=checks+1;
  execute 'reset role';
  execute 'set local role anon';
  assert not has_table_privilege(current_user,'public.auryn_documents','SELECT'), 'Anonymous private table grant retained'; checks:=checks+1;
  assert not has_table_privilege(current_user,'public.auryn_paper_lock','TRUNCATE'), 'Anonymous paper lock truncate grant retained'; checks:=checks+1;
  assert not has_function_privilege(current_user,'public.auryn_set_watch(text,boolean)','EXECUTE'), 'Anonymous watch RPC allowed'; checks:=checks+1;
  assert not has_function_privilege(current_user,'public.auryn_import_positions(uuid,jsonb)','EXECUTE'), 'Anonymous import RPC allowed'; checks:=checks+1;
  assert not has_function_privilege(current_user,'public.auryn_reserve_ai_request()','EXECUTE'), 'Anonymous AI reservation allowed'; checks:=checks+1;
  execute 'reset role';
  perform set_config('auryn.verification',jsonb_build_object('checks',checks,'status','passed','rollback_only',true,'broker_requests',0)::text,true);
end
$verification$;
select current_setting('auryn.verification')::jsonb as verification;
rollback;

